from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.agent.planner import Planner
from app.agent.router import IntentRouter
from app.eval.bad_cases import write_bad_case_replay

CASES_PATH = ROOT / "eval" / "planning_eval_cases.jsonl"
REPORT_DIR = ROOT / "data" / "reports"
RESULT_PATH = REPORT_DIR / "planning_eval_result.json"
REPORT_PATH = REPORT_DIR / "planning_eval_report.md"


def load_cases(path: Path = CASES_PATH) -> list[dict[str, Any]]:
    cases: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            cases.append(json.loads(line))
    return cases


def evaluate(cases_path: Path = CASES_PATH) -> dict[str, Any]:
    router = IntentRouter()
    planner = Planner()
    cases = load_cases(cases_path)

    route_hits = 0
    tool_hits = 0
    step_coverage_total = 0.0
    missing_tool_cases: list[dict[str, Any]] = []
    bad_cases: list[dict[str, Any]] = []
    case_results: list[dict[str, Any]] = []

    for case in cases:
        route = router.route(case["query"])
        plan = planner.plan(case["query"], route)
        actual_tools = [step.tool for step in plan.steps]
        actual_steps = [
            " ".join(
                [
                    step.action,
                    step.step_name,
                    step.description,
                    step.expected_output,
                ]
            ).lower()
            for step in plan.steps
        ]
        expected_tools = list(case.get("expected_tools") or [])
        expected_step_keywords = list(case.get("expected_step_keywords") or [])

        route_ok = route.type == case.get("expected_route")
        missing_tools = [tool for tool in expected_tools if tool not in actual_tools]
        extra_tools = [tool for tool in actual_tools if tool not in expected_tools]
        tools_ok = not missing_tools and not extra_tools
        covered_keywords = [
            keyword
            for keyword in expected_step_keywords
            if any(keyword.lower() in step_text for step_text in actual_steps)
        ]
        step_coverage = (
            len(covered_keywords) / len(expected_step_keywords)
            if expected_step_keywords
            else 1.0
        )
        case_passed = route_ok and tools_ok and step_coverage == 1.0

        route_hits += int(route_ok)
        tool_hits += int(tools_ok)
        step_coverage_total += step_coverage

        case_result = {
            "id": case.get("id", ""),
            "query": case["query"],
            "expected_route": case.get("expected_route"),
            "actual_route": route.type,
            "actual_intent": route.intent,
            "route_reason": route.reason,
            "expected_tools": expected_tools,
            "actual_tools": actual_tools,
            "missing_tools": missing_tools,
            "extra_tools": extra_tools,
            "expected_step_keywords": expected_step_keywords,
            "covered_step_keywords": covered_keywords,
            "step_coverage": round(step_coverage, 4),
            "route_ok": route_ok,
            "tools_ok": tools_ok,
            "passed": case_passed,
        }
        case_results.append(case_result)
        if missing_tools:
            missing_tool_cases.append(case_result)
        if not case_passed:
            bad_cases.append(case_result)

    total = max(1, len(cases))
    metrics = {
        "total_cases": len(cases),
        "route_accuracy": round(route_hits / total, 4),
        "tool_selection_accuracy": round(tool_hits / total, 4),
        "step_coverage": round(step_coverage_total / total, 4),
        "missing_tool_cases": missing_tool_cases,
        "bad_cases": bad_cases,
    }
    result_payload = {
        "metrics": metrics,
        "cases": case_results,
    }
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    RESULT_PATH.write_text(json.dumps(result_payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_bad_case_replay(planning_failed_cases=bad_cases)
    REPORT_PATH.write_text(render_report(metrics), encoding="utf-8")
    return metrics


def render_report(metrics: dict[str, Any]) -> str:
    scalar_metrics = {
        key: value
        for key, value in metrics.items()
        if key not in {"missing_tool_cases", "bad_cases"}
    }
    lines = [
        "# Planning Evaluation Report",
        "",
        "This report is generated by `python scripts/eval_planning.py` against the deterministic Router and Planner.",
        "It does not call DeepSeek, external APIs, LangGraph Executor, or tools.",
        "",
        "## Metrics",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
    ]
    for key, value in scalar_metrics.items():
        lines.append(f"| {key} | {value} |")

    lines.extend(["", "## Missing Tool Cases", ""])
    missing_tool_cases = metrics.get("missing_tool_cases", [])
    if not missing_tool_cases:
        lines.append("No missing tool cases.")
    else:
        for case in missing_tool_cases:
            lines.extend(
                [
                    f"### {case.get('id', '')}",
                    "",
                    f"- Query: {case.get('query', '')}",
                    f"- Expected tools: {case.get('expected_tools', [])}",
                    f"- Actual tools: {case.get('actual_tools', [])}",
                    f"- Missing tools: {case.get('missing_tools', [])}",
                    "",
                ]
            )

    lines.extend(["", "## Bad Cases", ""])
    bad_cases = metrics.get("bad_cases", [])
    if not bad_cases:
        lines.append("No bad planning cases.")
    else:
        for case in bad_cases:
            lines.extend(
                [
                    f"### {case.get('id', '')}",
                    "",
                    f"- Query: {case.get('query', '')}",
                    f"- Expected route: {case.get('expected_route', '')}",
                    f"- Actual route: {case.get('actual_route', '')}",
                    f"- Expected tools: {case.get('expected_tools', [])}",
                    f"- Actual tools: {case.get('actual_tools', [])}",
                    f"- Step coverage: {case.get('step_coverage', 0)}",
                    f"- Router reason: {case.get('route_reason', '')}",
                    "",
                ]
            )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    print(json.dumps(evaluate(), ensure_ascii=False, indent=2))
